-- DV-052 -- the Target model brought onto the contract, and the position question settled.
--
-- Five of the twelve Build Plan section 01 targets are solar-system bodies. A stored
-- J2000 coordinate for Jupiter is false the day after it is written, so coordinates are
-- now nullable and positionSource says which kind of target this is. The CHECK at the
-- bottom makes the invariant the database's business rather than the application's.
--
-- DESTRUCTIVE: currentVisibility, currentAltitude and qualityScore are dropped, and the
-- VisibilityRating enum with them. They cached observability, which both the contract
-- ("computed at request time from live ephemeris, never cached as a static list") and
-- Build Plan section 01 ("the scheduler computes these at request time -- never from a
-- static list") forbid. imagePreset, bestMonths and the old angularSize string go too:
-- the contract models size as a number in arcminutes.
--
-- Safe because no database holding real rows has been deployed. Target rows are seeded
-- catalogue data, regenerated by the seed.

-- ---------------------------------------------------------------------------
-- CATALOGUE PURGE -- READ BEFORE APPLYING TO ANY DATABASE YOU CARE ABOUT.
--
-- The new columns have no derivable value for an existing row. angularSizeArcmin
-- cannot be recovered from the old free-text angularSize ("190 x 60 arcmin"), and
-- opticalConfig and imagingProfile never existed. A backfill would mean inventing
-- the optical configuration for each target, which is a physical fact about the
-- instrument and not something a migration may guess.
--
-- So the catalogue is emptied and re-seeded from Build Plan section 01. Because
-- missions, bookings and captures reference targets with ON DELETE RESTRICT, they
-- are removed first. In this repository every such row is seeded demo data.
--
-- This is safe now, before launch, and never again. Once a real customer has an
-- observation, this migration would destroy it. It must not be re-run against a
-- populated database.
-- ---------------------------------------------------------------------------
