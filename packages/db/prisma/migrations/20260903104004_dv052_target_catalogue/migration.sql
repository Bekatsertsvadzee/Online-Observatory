-- AddConstraint
-- Exactly one position source, enforced where it cannot be bypassed. Prisma cannot
-- express a CHECK constraint, so it is written by hand.
ALTER TABLE "Target" ADD CONSTRAINT "target_position_source_consistent" CHECK (
  ("positionSource" = 'FIXED'
     AND "rightAscensionHours" IS NOT NULL
     AND "declinationDegrees"  IS NOT NULL
     AND "solarSystemBody"     IS NULL)
  OR
  ("positionSource" = 'EPHEMERIS'
     AND "solarSystemBody"     IS NOT NULL
     AND "rightAscensionHours" IS NULL
     AND "declinationDegrees"  IS NULL)
);
