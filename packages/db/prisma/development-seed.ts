export function assertDevelopmentSeedData() {
  const rows = [...DEMO_TARGETS, ...DEMO_MISSIONS, ...DEMO_CAPTURES];

  if (rows.some((row) => !row.isDemo)) {
    throw new Error("Development seed contains an unmarked record.");
  }

  if ([...DEMO_MISSIONS, ...DEMO_CAPTURES].some((row) => !row.simulated)) {
    throw new Error("Development observations must always be simulated.");
  }

  if (DEMO_TARGETS.some((target) => !target.catalogId.startsWith("DEMO-"))) {
    throw new Error("Development targets must use DEMO catalog identifiers.");
  }
}
